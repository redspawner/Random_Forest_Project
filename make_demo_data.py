        "- Craig-Schapiro R et al. *PLoS ONE* 2011;6:e18850 (Knight ADRC CSF panel); R package modeldata, "
        "dataset ad_data, via Rdatasets. Real CSF Abeta42, APOE genotype, clinical status.",
        "- Jansen WJ et al. Prevalence of cerebral amyloid pathology in persons without dementia: a meta-analysis. "
        "*JAMA* 2015;313:1924-38 (prevalence by age, APOE and cognitive status).",
        "- Ossenkoppele R et al. Prevalence of amyloid PET positivity in dementia syndromes: a meta-analysis. "
        "*JAMA* 2015;313:1939-49.",
        "- Mattsson-Carlgren N et al. *Nat Med* 2023, and Therriault J et al. 2023: plasma p-tau217 rises once "
        "amyloid accumulates and further with tau.",
        "- Mielke MM et al. *Nat Med* 2022; Pichet Binette A et al. 2023; Janelidze S et al. 2023: kidney function "
