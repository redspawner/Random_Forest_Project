"""Create the Excel template and the SYNTHETIC demo files.

    python make_demo_data.py

Outputs
    templates/patient_data_template.xlsx         empty template (expected layout)
    data/synthetic/synthetic_training_cohort.xlsx grey-zone patients WITH LP result (to train)
    data/synthetic/synthetic_new_patients.xlsx    new patients WITHOUT LP result (to predict)
    data/synthetic/synthetic_new_patients_answer_key.xlsx  their true LP result (to check)
"""

from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd

from greyzone_rf.config import PROJECT_ROOT, load_config
from greyzone_rf.synthetic import demo_new_patients, grey_zone_cohort
from greyzone_rf.template import write_template


def _write(df: pd.DataFrame, path: Path, note: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with pd.ExcelWriter(path, engine="openpyxl") as writer:
        df.to_excel(writer, sheet_name="Patients", index=False)
        pd.DataFrame({"README": [note]}).to_excel(writer, sheet_name="About", index=False)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--n-train", type=int, default=600, help="grey-zone training patients (default 600)")
    parser.add_argument("--seed", type=int, default=2024)
    args = parser.parse_args()

    cfg = load_config()
    gz = cfg["grey_zone"]
    lo, hi = gz["ptau217_lower"], gz["ptau217_upper"]
    template = write_template(cfg, PROJECT_ROOT / "templates" / "patient_data_template.xlsx")
    print(f"Template:        {template}")

    warning = ("SYNTHETIC DATA - artificial patients generated by greyzone_rf/synthetic.py for testing the "
               "software. Not real patients, not suitable for any scientific or clinical conclusion.")
    out = PROJECT_ROOT / "data" / "synthetic"
    train = grey_zone_cohort(args.n_train, lo, hi, seed=args.seed, prefix="SYN")
    _write(train, out / "synthetic_training_cohort.xlsx", warning)
    new, key = demo_new_patients(40, seed=args.seed + 1, lower=lo, upper=hi)
    _write(new, out / "synthetic_new_patients.xlsx", warning)
    _write(key, out / "synthetic_new_patients_answer_key.xlsx", warning)
    pos = (train["lp_result"] == "Positive").mean()
    print(f"Training cohort: {out / 'synthetic_training_cohort.xlsx'}  ({len(train)} patients, {pos:.0%} LP+)")
    print(f"New patients:    {out / 'synthetic_new_patients.xlsx'}  ({len(new)} patients)")
    print(f"Answer key:      {out / 'synthetic_new_patients_answer_key.xlsx'}")


if __name__ == "__main__":
    main()
