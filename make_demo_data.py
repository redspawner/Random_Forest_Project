def write_examples(cfg: dict, default_file: Path) -> None:
    """examples/: training file (= default dataset), new patients, and the 56-patient test sample."""
    import shutil

    gz = cfg["grey_zone"]
    lo, hi = gz["ptau217_lower"], gz["ptau217_upper"]
    ex = PROJECT_ROOT / "examples"
    shutil.copyfile(default_file, ex / "example_1_training_file.xlsx")
    shutil.copyfile(PROJECT_ROOT / "data" / "synthetic" / "synthetic_new_patients.xlsx",
                    ex / "example_2_new_patients_file.xlsx")

    grey = grey_zone_cohort(50, lo, hi, seed=DEFAULT_SEED + 7, prefix="TEST", real=True, version=GENERATOR)
    pool = grey_zone_cohort(20, lo, hi, seed=DEFAULT_SEED + 8, prefix="X", real=True, version=GENERATOR)
    from greyzone_rf.synthetic import real_clinical_base, simulator, _chs_cache

    pop = simulator(GENERATOR)(600, seed=DEFAULT_SEED + 9,
                               real_base=real_clinical_base(600, DEFAULT_SEED + 9, chs=_chs_cache()))
    low = pop[pop["ptau217"] < lo].iloc[[0]].copy()
    high = pop[pop["ptau217"] > hi].iloc[[0]].copy()
    typo, red, miss, comma = (pool.iloc[[i]].copy() for i in range(4))
    typo["egfr"] = 950
    red["atypical_features"] = 1
    for col in ["egfr", "creatinine", "triglycerides", "hemoglobin", "apoe4", "hypertension", "stroke",
                "clinical_stage"]:
        miss[col] = None
    comma["ptau217"] = f"{float(comma['ptau217'].iloc[0]):.3f}".replace(".", ",")
    specials = pd.concat([low, high, typo, red, miss, comma]).astype(object)
    specials["patient_id"] = ["TEST-LOW", "TEST-HIGH", "TEST-TYPO", "TEST-REDFLAG", "TEST-MISSING", "TEST-COMMA"]
    sample = _keep_config_columns(pd.concat([grey, specials], ignore_index=True), cfg)
    key = sample[["patient_id", "lp_result"]].copy()
    _write(sample.drop(columns=["lp_result"]), ex / "test_sample_56_patients.xlsx")
    cases = pd.DataFrame({
        "patient_id": ["TEST-LOW", "TEST-HIGH", "TEST-TYPO", "TEST-REDFLAG", "TEST-MISSING", "TEST-COMMA"],
        "tests": ["p-tau217 below the grey zone", "p-tau217 above the grey zone", "eGFR = 950 (impossible)",
                  "atypical_features = 1", "8 of the variables blank", "p-tau217 written with a decimal comma"],
        "expected": ["NOT APPLICABLE (Stage-1 negative)", "NOT APPLICABLE (Stage-1 positive)", "CHECK DATA",
                     "INCONCLUSIVE (red flag)", "INCONCLUSIVE (insufficient data)", "read correctly and classified"],
    })
    with pd.ExcelWriter(ex / "test_sample_56_patients_answer_key.xlsx", engine="openpyxl") as writer:
        key.to_excel(writer, sheet_name="LP results", index=False)
        cases.to_excel(writer, sheet_name="Special cases", index=False)
    print(f"Examples:        {ex} (training, new patients, 56-patient test sample + answer key)")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--overwrite-default", action="store_true",
                        help="regenerate the preserved default training dataset (changes the shipped model!)")
    args = parser.parse_args()

    cfg = load_config()
    gz = cfg["grey_zone"]
    lo, hi = gz["ptau217_lower"], gz["ptau217_upper"]
    print(f"Template:        {write_template(cfg, PROJECT_ROOT / 'templates' / 'patient_data_template.xlsx')}")

    default_file = PROJECT_ROOT / cfg["default_model"]["training_file"]
    if args.overwrite_default or not default_file.exists():
        train = _keep_config_columns(grey_zone_cohort(DEFAULT_N, lo, hi, seed=DEFAULT_SEED, prefix="SYN", real=True,
                                                       version=GENERATOR), cfg)
        _write(train, default_file)
        write_dataset_card(default_file.parent / "DATASET_CARD.md", default_file, train, cfg)
        print(f"Default dataset: {default_file}  ({len(train)} patients) + DATASET_CARD.md")
        print("  -> retrain the shipped model with:  python train.py --default")
    else:
        print(f"Default dataset: {default_file} kept unchanged (use --overwrite-default to regenerate)")

    out = PROJECT_ROOT / "data" / "synthetic"
    new, key = demo_new_patients(40, seed=DEFAULT_SEED + 1, lower=lo, upper=hi, real=True, version=GENERATOR)
    new = _keep_config_columns(new, cfg)
    _write(new, out / "synthetic_new_patients.xlsx")
    _write(key, out / "synthetic_new_patients_answer_key.xlsx")
    print(f"New patients:    {out / 'synthetic_new_patients.xlsx'}  ({len(new)} patients)")
    print(f"Answer key:      {out / 'synthetic_new_patients_answer_key.xlsx'}")
    write_examples(cfg, default_file)


if __name__ == "__main__":
    main()
